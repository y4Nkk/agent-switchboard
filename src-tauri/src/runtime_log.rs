fn is_runtime_log_file(path: &Path) -> bool {
    let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
        return false;
    };
    name == format!("{LOG_FILE_STEM}.log")
        || (name.starts_with(&format!("{LOG_FILE_STEM}_")) && name.ends_with(".log"))
}

impl RuntimeLogEntry {
    fn is_valid(&self) -> bool {
        if !self.at.ends_with('Z') || DateTime::parse_from_rfc3339(&self.at).is_err() {
            return false;
        }
        match self.level {
            RuntimeLogSeverity::Debug | RuntimeLogSeverity::Info | RuntimeLogSeverity::Warn => {
                self.error_code.is_none()
            }
            RuntimeLogSeverity::Error => self.error_code.as_deref().is_some_and(is_error_code),
        }
    }
}

fn is_error_code(code: &str) -> bool {
    !code.is_empty()
        && code.len() <= 96
        && code
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
}

